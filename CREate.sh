cmd_call ()
{
  ### handle options
  parallel=20
  window_size=200
  export splitLines=10000000
  infileMax=''
  infileEach=''
  prog_compression=gzip
  while getopts i:m:c:w:p:z: opt
  do
    case ${opt} in
    i) infile=${OPTARG};;
    m) infileMax=${OPTARG};;
    c) chrom_sizes=${OPTARG};;
    w) window_size=${OPTARG};;
    p) parallel=${OPTARG};;
    z) prog_compression=${OPTARG};;
    *) usage;;
    esac
  done
  if [ ! -n "${infile-}" ]; then usage; fi
  if [ ! -n "${chrom_sizes-}" ]; then usage; fi

  printf "### call\n"  >&2

  ### setup for later
  tmpdir=$(mktemp -d -p ${TMPDIR:-/tmp})
  trap "test -d $tmpdir && rm -rf $tmpdir" 0 1 2 3 15
  window_half_size=$(( $window_size / 2 ))
  window_double_size=$(( $window_size * 2 ))

  SORT_OPT_BASE="--batch-size=100"
  SORT_OPT_BED="${SORT_OPT_BASE} -k1,1 -k2,2n -k3,3n"
  SORT_OPT_BED_NAME="${SORT_OPT_BASE} -k4,4"
  SORT_OPT_NAME="${SORT_OPT_BASE} -k1,1"

  PROG_COMP="$prog_compression -c"
  PROG_DECOMP="$prog_compression -d"
  if [ "${prog_compression}" = "zstd"  ]; then
    PROG_COMP="$PROG_COMP -T${parallel} "
  fi

  printf "### call: prepare target positions\n" >&2 
  prep_input $infile $window_double_size

  printf "### call: compute neighbouring signals\n" >&2
  accumulate_neiboring_signals \
    ${tmpdir}/potential_center.bg.COMP \
    ${tmpdir}/infile.fwd.bw \
    ${tmpdir}/infile.rev.bw \
    $window_size \
  | $PROG_COMP \
  > ${tmpdir}/potential_center.txt.COMP

  printf "### call: select divergent regions\n" >&2
  cat ${tmpdir}/potential_center.txt.COMP \
  | $PROG_DECOMP \
  | classify_convergent_divergent \
      ${tmpdir}/potential_center_conv.bed \
      ${tmpdir}/potential_center_divergent.bed

  printf "### call: find cores with left/right boundaries\n"  >&2
  find_max_scores \
    ${tmpdir}/potential_center_divergent.bed \
    ${tmpdir}/infile.density.fwd.bg \
    ${tmpdir}/infile.density.rev.bg \
    $window_size \
  > ${tmpdir}/potential_center_divergent_with_core.bed

  printf "### call: tighten\n"  >&2
  tighten_unidirectional ${tmpdir}/potential_center_divergent_with_core.bed \
  > ${tmpdir}/potential_center_divergent_with_core_tight.bed

  printf "### call: counts_fr\n"  >&2
  total=$( gunzip -c ${infile} | awk '{sum += $5 * ($3-$2)}END{print sum}' )
  counts_fr ${tmpdir}/potential_center_divergent_with_core_tight.bed ${infileMax} \
  | awk --assign total=$total 'BEGIN{OFS="\t"}{
      if (match( $4, /counts:[-.0-9,]+/)) {
        c = substr($4, RSTART, RLENGTH)
        sub("counts:", "", c)
        c += 0
      }
      tpm = 1e6 * c / total
      $4 = $4"|total:"total"|tpm:"tpm
      $5 = tpm
      print
    }'
}



cmd_eachcount ()
{
  ### handle options
  parallel=20
  infile=
  infileEach=
  while getopts i:e:p:o: opt
  do
    case ${opt} in
    i) infile=${OPTARG};;
    e) infileEach=${OPTARG};;
    p) parallel=${OPTARG};;
    o) out_prefix=${OPTARG};;
    *) usage;;
    esac
  done
  if [ ! -n "${infile-}" ]; then usage; fi
  if [ ! -n "${infileEach-}" ]; then usage; fi
  if [ ! -n "${out_prefix-}" ]; then usage; fi
  printf "### eachcount\n"  >&2

  ### setup for later
  tmpdir=$(mktemp -d -p ${TMPDIR:-/tmp})
  trap "test -d $tmpdir && rm -rf $tmpdir" 0 1 2 3 15

  mkdir -p ${tmpdir}/each
  tar xvf ${infileEach} -C ${tmpdir}/each/


  ###
  ### assign tentative name
  ###
  gunzip -c ${infile} \
  | grep -v ^# \
  | sort -k1,1 -k2,2n \
  | awk '{printf "LN%012d\t%s\n", NR, $0}' \
  > ${tmpdir}/LN_infile.txt

  ###
  ### prep regions (core + extended for forward or reverse)
  ###
  cat ${tmpdir}/LN_infile.txt \
  | awk 'BEGIN{OFS="\t"}{
    chr=$2;start=$3;stop=$4;core_start=$8;core_stop=$9;name=$1
    print chr, core_start, stop, name
  }' > ${tmpdir}/fwd.bed

  cat ${tmpdir}/LN_infile.txt \
  | awk 'BEGIN{OFS="\t"}{
    chr=$2;start=$3;stop=$4;core_start=$8;core_stop=$9;name=$1
    print chr, start, core_stop, name
  }' > ${tmpdir}/rev.bed


  ###
  ### prep totals
  ###
  find ${tmpdir}/each/ -name '*.fwd.bw' \
  | xargs -P ${parallel} -I % sh -c \
     "bigWigToBedGraph % /dev/stdout | awk '{sum += \$4 * (\$3 - \$2)}END{print \"%,\"sum}' > %.totalFwd.txt " \

  find ${tmpdir}/each/ -name '*.fwd.bw.totalFwd.txt' \
  | xargs -I % cat % \
  | sed 's/.fwd.bw,/\t/'  \
  | sed 's/^.*\///'  \
  | sort -k1,1 \
  > ${tmpdir}/totalsFwd.txt


  find ${tmpdir}/each/ -name '*.rev.bw' \
  | xargs -P ${parallel} -I % sh -c \
     "bigWigToBedGraph % /dev/stdout | awk '{sum += \$4 * (\$3 - \$2)}END{print \"%,\"sum}' > %.totalRev.txt " \

  find ${tmpdir}/each/ -name '*.rev.bw.totalRev.txt' \
  | xargs -I % cat % \
  | sed 's/.rev.bw,/\t/'  \
  | sed 's/^.*\///'  \
  | sort -k1,1 \
  > ${tmpdir}/totalsRev.txt

  join -t "	" ${tmpdir}/totalsFwd.txt ${tmpdir}/totalsRev.txt \
  | awk 'BEGIN{OFS="\t"}{print $1,$2+$3}' \
  > ${tmpdir}/totals.txt


  ###
  ### counts in parallel
  ###
  cut -f 1 ${tmpdir}/totals.txt \
  | xargs -P ${parallel} -I % sh -c  \
    "bigWigAverageOverBed ${tmpdir}/each/%.fwd.bw ${tmpdir}/fwd.bed ${tmpdir}/each/%.fwd.bw.txt; gzip ${tmpdir}/each/%.fwd.bw.txt"

  cut -f 1 ${tmpdir}/totals.txt \
  | xargs -P ${parallel} -I % sh -c  \
    "bigWigAverageOverBed ${tmpdir}/each/%.rev.bw ${tmpdir}/rev.bed ${tmpdir}/each/%.rev.bw.txt; gzip ${tmpdir}/each/%.rev.bw.txt"


  ###
  ### merge each counts 
  ###
  gunzip -c ${tmpdir}/each/$( head -1 ${tmpdir}/totals.txt | cut -f 1 ).fwd.bw.txt.gz \
  | cut -f 1 \
  | tee ${tmpdir}/count.fwd.txt \
  > ${tmpdir}/count.rev.txt 

  for X in $( cat ${tmpdir}/totals.txt | cut -f 1  )
  do
    X=${tmpdir}/each/${X}.fwd.bw.txt.gz
    gunzip -c $X \
    | cut -f 1,4 \
    | join -t "	" ${tmpdir}/count.fwd.txt - \
    > ${tmpdir}/count.fwd.txt.tmp
    mv -f ${tmpdir}/count.fwd.txt.tmp ${tmpdir}/count.fwd.txt
  done

  for X in $( cat ${tmpdir}/totals.txt | cut -f 1  )
  do
    X=${tmpdir}/each/${X}.rev.bw.txt.gz
    gunzip -c $X \
    | cut -f 1,4 \
    | join -t "	" ${tmpdir}/count.rev.txt - \
    > ${tmpdir}/count.rev.txt.tmp
    mv -f ${tmpdir}/count.rev.txt.tmp ${tmpdir}/count.rev.txt
  done


  ###
  ### merge fwd & rev
  ###
  cat ${tmpdir}/count.fwd.txt \
  | awk '{buf=$2;for(i=3;i <=NF; i++){buf=buf","$i};print $1"\t"buf}' \
  > ${tmpdir}/count.fwd.txt.tmp
  mv -f ${tmpdir}/count.fwd.txt.tmp ${tmpdir}/count.fwd.txt


  cat ${tmpdir}/count.rev.txt \
  | awk '{buf=$2;for(i=3;i <=NF; i++){buf=buf","$i};print $1"\t"buf}' \
  > ${tmpdir}/count.rev.txt.tmp
  mv -f ${tmpdir}/count.rev.txt.tmp ${tmpdir}/count.rev.txt


  join -t "	" \
    ${tmpdir}/count.fwd.txt \
    ${tmpdir}/count.rev.txt \
  | sort -k1,1 \
  | awk 'BEGIN{OFS="\t"}{
      fwdN=split($2,eachCountsFwd,",");
      revN=split($3,eachCountsRev,",");
      i = 1
      eachCounts = eachCountsFwd[i] + eachCountsRev[i]
      for (i=2; i<=fwdN; i++) {
        eachCounts = eachCounts","(eachCountsFwd[i] + eachCountsRev[i])
      }
      print $1, eachCounts, $2, $3
    }' \
  > ${tmpdir}/count.fwdrev.txt


  cut -f 1 ${tmpdir}/totals.txt \
  | xargs -L 1 echo -n " " \
  | sed -e 's/ \+/,/g' \
  | sed -e 's/^,//' \
  | awk '{
      printf("#chrom\tchromStart\tchromEnd\tname\tscore\tstrand\tthickStart\tthickEnd\titemRgb\tcounts[%s]\tfwdCounts[.]\trevCounts[.]\n" , $0 )
    }' \
  > ${tmpdir}/out_eachcounts.bed9pls3


  cat ${tmpdir}/count.fwdrev.txt \
  | join -t "	" ${tmpdir}/LN_infile.txt  - \
  | cut -f 2- \
  >> ${tmpdir}/out_eachcounts.bed9pls3


  gzip -c ${tmpdir}/out_eachcounts.bed9pls3 > ${out_prefix}_eachcounts.bed9pls3.gz
  cp -f ${tmpdir}/totals.txt ${out_prefix}_eachcounts_totals.txt


  cat <<EOF | R --slave | gzip -c > ${out_prefix}_eachcounts.txt.gz
  library(tidyverse)

  buf = read_tsv("${out_prefix}_eachcounts_totals.txt", col_names=F, comment = "#")
  totals = unlist( buf[,2] )
  names(totals) = unlist( buf[,1] )

  bed = read_tsv("${out_prefix}_eachcounts.bed9pls3.gz", col_names=T, comment = "")
  colnames(bed)[10] = "counts"

  counts = bed %>% 
    select("name", counts) %>%
    separate( counts, sep=",", into=names(totals) )

  counts = rbind(
    c( "01STAT:TOTAL", totals ),
    counts
  )

  write.table(counts, sep="\t", quote = F,row.names=F)
EOF


}



cmd_filter ()
{
  ### handle options
  max_directionality=1
  min_directionality=0
  max_counts=-1
  min_counts=4
  max_tpm=-1
  min_tpm=0
  min_counts_in_each_strand=0
  min_ctssMax=0
  min_ctssMax_in_each_strand=0
  max_length=-1
  min_length=5
  invert_match="false"

  while getopts D:d:C:c:T:t:e:x:y:l:L:v opt
  do
    case ${opt} in
    D) max_directionality=${OPTARG};;
    d) min_directionality=${OPTARG};;
    C) max_counts=${OPTARG};;
    c) min_counts=${OPTARG};;
    T) max_tpm=${OPTARG};;
    t) min_tpm=${OPTARG};;
    e) min_counts_in_each_strand=${OPTARG};;
    x) min_ctssMax=${OPTARG};;
    y) min_ctssMax_in_each_strand=${OPTARG};;
    L) max_length=${OPTARG};;
    l) min_length=${OPTARG};;
    v) invert_match="true";;
    *) usage;;
    esac
  done

  printf "### filter\n"  >&2


  awk \
    --assign max_directionality=$max_directionality \
    --assign min_directionality=$min_directionality \
    --assign max_counts=$max_counts \
    --assign min_counts=$min_counts \
    --assign max_tpm=$max_tpm \
    --assign min_tpm=$min_tpm \
    --assign min_counts_in_each_strand=$min_counts_in_each_strand \
    --assign min_ctssMax=$min_ctssMax \
    --assign min_ctssMax_in_each_strand=$min_ctssMax_in_each_strand \
    --assign max_length=$max_length \
    --assign min_length=$min_length \
    --assign invert_match=$invert_match \
  'BEGIN{OFS="\t"}{

    if (match( $0, /directionality:[-.0-9]+/)) {
      s = substr($0, RSTART, RLENGTH)
      sub("directionality:", "", s)
      d = s + 0;
      if (d < 0) { d = d * -1}
    }

    if (match( $0, /counts:[-.0-9]+/)) {
      c = substr($0, RSTART, RLENGTH)
      sub("counts:", "", c)
      c += 0;
    }
    if (match( $0, /countsFwd:[-.0-9]+/)) {
      f = substr($0, RSTART, RLENGTH)
      sub("countsFwd:", "", f)
      f += 0;
    }
    if (match( $0, /countsRev:[-.0-9]+/)) {
      r = substr($0, RSTART, RLENGTH)
      sub("countsRev:", "", r)
      r += 0;
    }

    cm = 0; cmf = 0 ; cmr = 0;
    if (match( $0, /ctssMax:[-.0-9]+/)) {
      cm = substr($0, RSTART, RLENGTH)
      sub("ctssMax:", "", cm)
      cm += 0;
    }
    if (match( $0, /ctssMaxFwd:[-.0-9]+/)) {
      cmf = substr($0, RSTART, RLENGTH)
      sub("ctssMaxFwd:", "", cmf)
      cmf += 0;
    }
    if (match( $0, /ctssMaxRev:[-.0-9]+/)) {
      cmr = substr($0, RSTART, RLENGTH)
      sub("ctssMaxRev:", "", cmr)
      cmr += 0;
    }
    if (match( $0, /tpm:[-.0-9]+/)) {
      tpm = substr($0, RSTART, RLENGTH)
      sub("tpm:", "", tpm)
      tpm += 0;
    }

    if ( ( cm == 0 ) && ( min_ctssMax > 0) ) {
      print "Error: No ctssMax found. Related filters cannot be used.\n" > "/dev/stderr"
      exit 1
    }
    if ( ( cm == 0 ) && ( min_ctssMax_in_each_strand > 0) ) {
      print "Error: No ctssMax found. Related filters cannot be used.\n" > "/dev/stderr"
      exit 1
    }

    len = $3 - $2

    flagM = "true"
    if      ( d > max_directionality )           { flagM = "false" }
    else if ( d < min_directionality )           { flagM = "false" }

    else if ( ( max_counts >= 0) &&
              ( c > max_counts ) )               { flagM = "false" }
    else if ( c < min_counts )                   { flagM = "false" }

    else if ( ( max_tpm >= 0  ) &&
              ( tpm > max_tpm ) )                { flagM = "false" }
    else if ( tpm < min_tpm )                    { flagM = "false" }

    else if ( f < min_counts_in_each_strand )    { flagM = "false" }
    else if ( r < min_counts_in_each_strand )    { flagM = "false" }

    else if ( cm < min_ctssMax )                 { flagM = "false" }
    else if ( cmf < min_ctssMax_in_each_strand ) { flagM = "false" }
    else if ( cmr < min_ctssMax_in_each_strand ) { flagM = "false" }

    else if ( ( max_length >= 0  ) &&
              ( len > max_length ) )                { flagM = "false" }
    else if ( len < min_length )                    { flagM = "false" }


    # invert
    if ( invert_match == "true" ) {
      if ( flagM == "true" ) { flagM = "false" } else { flagM = "true" }
    }
    if ( flagM == "true" ) { print }
  }'
}



cmd_classify ()
{
