ctssbed_to_bg ()
{
  local strand=$1

  awk --assign strand=$strand 'BEGIN{OFS="\t"}{
    if($6 == strand )
    {
      for (i=$2; i < $3; i++) 
      {
        print $1,i,i+1,$5
      }
    }
  }' \
  | sort $SORT_OPT_BED
}


ctssGzBed_to_TpmBg ()
{
  local infile=$1
  local strand=$2

  total=$( gunzip -c $infile | awk '{total += $5 * ($3 - $2)}END{print total}' )
  gunzip -c $infile \
  | ctssbed_to_bg $strand \
  | awk --assign total=$total \
      '{$4 = $4 * 1e6 / total ; printf "%s\t%d\t%d\t%.2f\n", $1, $2, $3, $4}'
}



bg_to_bed4 ()
{
  awk 'BEGIN{OFS="\t"}{print $1,$2,$3,$1"|"$2"|"$3}'
}


ctss_density ()
{
  local infile_bed4=$1
  local infile_bw=$2
  local density_width=$3
  local outfile_bg=$4

  cat ${chrom_sizes} \
  | awk --assign density_width=$density_width 'BEGIN{OFS="\t"}{print $1, density_width, $2 - density_width}' \
  > ${infile_bed4}.tmp.scope

  intersectBed -u -wa -a ${infile_bed4} -b ${infile_bed4}.tmp.scope \
  | split -l ${splitLines} - ${infile_bed4}.tmp.non_boundary.split.

  ls ${infile_bed4}.tmp.non_boundary.split.* \
  | xargs -P ${parallel} -I % bigWigAverageOverBed -sampleAroundCenter=$density_width $infile_bw % %.OUT

  cat ${infile_bed4}.tmp.non_boundary.split.*.OUT \
  | cut -f 1,5 \
  | sed -e 's/|/\t/g' \
  | sort $SORT_OPT_BED \
  > ${outfile_bg}

  rm -f ${infile_bed4}.tmp.non_boundary.split.*
}



