  | sed -e 's/,/\t/g' \
  | sort -k1,1 -k2,2n --parallel=$parallel \
  > ${tmpdir}/fwd_target.bed.wMatchH.bg

  unionBedGraphs -i \
    ${tmpdir}/fwd_unmatchG.sam.bg \
    ${tmpdir}/fwd_matchG.sam.bg \
    ${tmpdir}/fwd_target.bed.wUnmatchG.bg \
